package sc.fidelis.engine;

import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

import sc.fidelis.engine.api.ActionRequest.Operations;
import sc.fidelis.engine.api.Enums.OperationState;
import sc.fidelis.engine.api.Enums.Provenance;
import sc.fidelis.engine.api.HistoryRecord;

/**
 * Generates a classic-Fiji macro from the structured history (docs D07 section 4, rules G1 to G11).
 * Images are addressed by ids captured at run time ({@code idN = getImageID()}) and selected before each
 * step; result-affecting globals are restored first; steps that cannot be expressed are skipped with a comment.
 */
final class MacroExport {
    private MacroExport() {}

    static String generate(List<HistoryRecord> history, String sessionId, String runtime) {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by Fidelis from session ").append(sessionId).append("; ").append(runtime).append(".\n");
        sb.append("// Replays the structured history; steps that are not macro-expressible are listed as comments.\n");

        // G1: globals as recorded before the first step
        Map<String, String> g = null;
        for (HistoryRecord r : history) {
            if (!r.globalsBefore().isEmpty()) {
                g = r.globalsBefore();
                break;
            }
        }
        sb.append("// ---- Result-affecting settings (restored before replay) ----\n");
        if (g != null) {
            sb.append("setOption(\"BlackBackground\", ").append("true".equals(g.get("blackBackground"))).append(");\n");
            String m = g.getOrDefault("measurements", "");
            sb.append("run(\"Set Measurements...\", \"").append(m.isEmpty() ? "" : m + " ").append("redirect=None decimal=")
                    .append(g.getOrDefault("precision", "3")).append("\");\n");
            StringBuilder conv = new StringBuilder();
            if ("true".equals(g.get("doScaling"))) conv.append("scale");
            if ("true".equals(g.get("weightedColor"))) conv.append(conv.length() > 0 ? " " : "").append("weighted");
            sb.append("run(\"Conversions...\", \"").append(conv).append("\");\n");
        } else {
            sb.append("// (no settings recorded)\n");
        }

        // undone steps are not replayed
        Map<String, HistoryRecord> byAction = new LinkedHashMap<>();
        for (HistoryRecord r : history) byAction.put(r.actionId(), r);
        Set<String> undone = new HashSet<>();
        for (HistoryRecord r : history) {
            if (Operations.UNDO.equals(r.commandId()) && r.params().get("undoneActionId") != null)
                undone.add(String.valueOf(r.params().get("undoneActionId")));
        }

        sb.append("// ---- Steps ----\n");
        Map<String, String> vars = new LinkedHashMap<>();
        int step = 0;
        for (HistoryRecord r : history) {
            step++;
            Object pid = r.params().get("parentActionId");
            if (pid != null) { // covered by the parent CODE step when that has macro lines
                HistoryRecord parent = byAction.get(String.valueOf(pid));
                if (parent != null && !parent.macroLines().isEmpty()) continue;
                if (r.macroLines().isEmpty()) continue;
            }
            if (Operations.UNDO.equals(r.commandId())) continue;
            if (undone.contains(r.actionId())) {
                sb.append("// step ").append(step).append(" undone: ").append(r.label()).append("\n");
                continue;
            }
            if (r.outcome() != OperationState.COMPLETED) {
                sb.append("// step ").append(step).append(" not applied (").append(r.outcome()).append("): ").append(r.label()).append("\n");
                continue;
            }
            if (r.provenance() == Provenance.UNRECORDABLE || (r.macroLines().isEmpty() && r.commandId() == null)) {
                sb.append("// step ").append(step).append(" not macro-expressible: ").append(r.label()).append("\n");
                continue;
            }
            if (r.macroLines().isEmpty()) continue; // state-only steps (ROI list bookkeeping, close of nothing)
            String docId = r.target() == null ? null : r.target().document().value();
            boolean isInput = Operations.OPEN.equals(r.commandId()) || Operations.NEW_IMAGE.equals(r.commandId());
            if (docId != null && !isInput) {
                String v = vars.get(docId);
                if (v != null) sb.append("selectImage(").append(v).append(");\n");
                else sb.append("// document ").append(docId).append(" was not created by a recorded step; selecting by focus\n");
            }
            if (r.provenance() == Provenance.NATIVE && !r.macroExact())
                sb.append("// observed from the Fiji interface; parameters may be incomplete\n");
            for (String line : r.macroLines()) sb.append(line).append('\n');
            if (Operations.OPEN.equals(r.commandId()) && r.params().get("sha256") != null) {
                sb.setLength(sb.length() - 1);
                sb.append("   // sha256: ").append(r.params().get("sha256")).append('\n');
            }
            // G2: bind ids of images this step created
            List<String> created = createdBy(r);
            if (created.size() == 1) {
                String v = "id" + created.get(0).replace("doc-", "");
                vars.put(created.get(0), v);
                sb.append(v).append(" = getImageID();\n");
            } else if (created.size() > 1) {
                sb.append("// step ").append(step).append(" created ").append(created.size())
                        .append(" images; only the active one is bound to a variable\n");
                String last = created.get(created.size() - 1);
                String v = "id" + last.replace("doc-", "");
                vars.put(last, v);
                sb.append(v).append(" = getImageID();\n");
            }
            if (Operations.CLOSE.equals(r.commandId()) && docId != null) vars.remove(docId);
        }
        return sb.toString();
    }

    @SuppressWarnings("unchecked")
    private static List<String> createdBy(HistoryRecord r) {
        Object d = r.params().get("document");
        if (d != null && (Operations.OPEN.equals(r.commandId()) || Operations.NEW_IMAGE.equals(r.commandId()))) return List.of(String.valueOf(d));
        Object c = r.params().get("createdDocuments");
        if (c instanceof List<?> l) return (List<String>) l;
        return List.of();
    }
}
