#!/usr/bin/env python3
"""Prepare only a fresh private synthetic-import app. Does not launch or touch the normal app."""
import json, pathlib, plistlib, shutil, subprocess, sys
ROOT=pathlib.Path(__file__).resolve().parent.parent

def main():
    fixture=pathlib.Path(sys.argv[1]).resolve()
    if fixture.parent != (ROOT/'.local/synthetic-import-fixtures').resolve() or not (fixture/'nonce').is_file():
        raise RuntimeError('Use a freshly owned synthetic fixture directory.')
    nonce=(fixture/'nonce').read_text().strip()
    if fixture.name != nonce or len(nonce)!=36:
        raise RuntimeError('Fixture identity mismatch.')
    app=fixture/'QuPathImportFixture.app'
    if app.exists():raise RuntimeError('Never overwrite a fixture app.')
    jdk=next((ROOT/'.local/jdk').glob('*/Contents/Home'))
    stock=ROOT/'.local/qupath-package/QuPath-0.7.0-arm64-app.pkg/Payload/QuPath-0.7.0-arm64.app'
    classes=fixture/'classes';classes.mkdir()
    sources=ROOT/'adapters/qupath/src/test/java/science/luma/qupath'
    subprocess.run([str(jdk/'bin/javac'),'--release','25','-cp',str(stock/'Contents/app/*')+':'+str(ROOT/'dist/luma-qupath-bridge.jar'),'-d',str(classes),*[str(sources/name) for name in ['MemoryPreferencesFactory.java','SyntheticImportPreferences.java','SyntheticImportFixture.java']]],check=True)
    subprocess.run([str(jdk/'bin/jar'),'--create','--file',str(fixture/'fixture.jar'),'-C',str(classes),'.'],check=True)
    subprocess.run([str(ROOT/'script/package-qupath.sh'),'--output',str(app)],cwd=ROOT,check=True)
    # Freeze the fixture's bridge bytes and build identity; normal launcher and bridge-token are untouched.
    (fixture/'dist').mkdir();shutil.copy2(ROOT/'dist/luma-qupath-bridge.jar',fixture/'dist/luma-qupath-bridge.jar')
    shutil.copy2(ROOT/'.local/bridge-build.json',fixture/'.local/bridge-build.json')
    bridge=app/'Contents/app/luma-qupath-bridge.jar';bridge.unlink();bridge.symlink_to(fixture/'dist/luma-qupath-bridge.jar')
    (app/'Contents/app/fixture.jar').symlink_to(fixture/'fixture.jar')
    config=app/'Contents/app/QuPath-0.7.0-arm64.cfg'
    value=config.read_text().replace('[JavaOptions]','app.classpath=$APPDIR/fixture.jar\n\n[JavaOptions]')
    value+='\njava-options=-Djava.util.prefs.PreferencesFactory=science.luma.qupath.SyntheticImportPreferences\n'
    value+='java-options=-Dluma.synthetic.root='+str(fixture)+'\njava-options=-Dqupath.startup.script='+str(fixture/'startup.groovy')+'\n'
    value+='java-options=-Djavafx.cachedir='+str(fixture/'javafx-cache')+'\njava-options=-Dorg.bytedeco.javacpp.cachedir='+str(fixture/'javacpp-cache')+'\n'
    config.write_text(value)
    # JSON string syntax is also valid Groovy here; all source is generated by the trusted test harness.
    (fixture/'startup.groovy').write_text('science.luma.qupath.SyntheticImportFixture.start('+json.dumps(str(fixture))+')\n')
    metadata=plistlib.loads((app/'Contents/Info.plist').read_bytes());metadata.update(CFBundleIdentifier='science.luma.synthetic-import.'+nonce,CFBundleName='Luma synthetic import fixture')
    (app/'Contents/Info.plist').write_bytes(plistlib.dumps(metadata))
    subprocess.run(['codesign','--force','--sign','-',str(app)],check=True)
if __name__=='__main__':main()
