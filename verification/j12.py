"""Independent reference macro for journey J-12 (docs D16) on a fixture (docs A30 CR-A30-02).

Hand-written and table-driven: every step carries its explicit option string, taken from
docs/data/commands-core-parameters.csv. Booleans that are absent are false (macro mode). Nothing here
imports or shares templates with the product's macro generator.

Step order follows the verification brief (T3):
  open -> Subtract Background (rolling=50) -> Gaussian Blur (sigma=2) -> setAutoThreshold("Otsu dark")
  -> Convert to Mask -> Watershed -> Set Measurements -> Measure -> Analyze Particles -> saveAs Tiff
BlackBackground is set explicitly before the first step (D16 J-12 step 7 records it as a global).
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
DUMPER = HERE / "dumper.js"

BLACK_BACKGROUND = True
THRESHOLD = "Otsu dark"
SET_MEASUREMENTS = "area mean min integrated redirect=None decimal=9"
PARTICLES = "size=20-Infinity show=Masks display clear include summarize add"
PARTICLES_NO_ADD = "size=20-Infinity show=Masks display clear include summarize"


@dataclass(frozen=True)
class Step:
    tag: str
    label: str
    command_id: str  # catalogue row used to pick the reference mode (docs/data/commands.csv)
    macro: str  # macro line(s); {path} {out} are substituted


def q(path: str | Path) -> str:
    """Quote a path as an ImageJ macro string (forward slashes; no escaping needed on Windows paths)."""
    s = str(path).replace("\\", "/")
    if '"' in s:
        raise ValueError("double quote in path")
    return f'"{s}"'


def steps(fixture_path: Path, saved_tiff: Path, with_add: bool = True, threshold: str = THRESHOLD) -> list[Step]:
    particles = PARTICLES if with_add else PARTICLES_NO_ADD
    return [
        Step("s01_open", "open", "ij1:File>Open...", f"open({q(fixture_path)}); id1 = getImageID();"),
        Step("s02_subtract_background", 'run("Subtract Background...", "rolling=50")',
             "ij1:Process>Subtract Background...",
             'selectImage(id1); run("Subtract Background...", "rolling=50");'),
        Step("s03_gaussian_blur", 'run("Gaussian Blur...", "sigma=2")',
             "ij1:Process>Filters>Gaussian Blur...",
             'selectImage(id1); run("Gaussian Blur...", "sigma=2");'),
        Step("s04_threshold", f'setAutoThreshold("{threshold}")', "ij1:Image>Adjust>Threshold...",
             f'selectImage(id1); setAutoThreshold("{threshold}");'),
        Step("s05_convert_to_mask", 'run("Convert to Mask")', "ij1:Process>Binary>Convert to Mask",
             'selectImage(id1); run("Convert to Mask");'),
        Step("s06_watershed", 'run("Watershed")', "ij1:Process>Binary>Watershed",
             'selectImage(id1); run("Watershed");'),
        Step("s07_set_measurements", f'run("Set Measurements...", "{SET_MEASUREMENTS}")',
             "ij1:Analyze>Set Measurements...",
             f'selectImage(id1); run("Set Measurements...", "{SET_MEASUREMENTS}");'),
        Step("s08_measure", 'run("Measure")', "ij1:Analyze>Measure",
             'selectImage(id1); run("Measure");'),
        Step("s09_analyze_particles", f'run("Analyze Particles...", "{particles}")',
             "ij1:Analyze>Analyze Particles...",
             f'selectImage(id1); run("Analyze Particles...", "{particles}");'),
        Step("s10_save_tiff", f'saveAs("Tiff", {q(saved_tiff)})', "ij1:File>Save As>Tiff...",
             f'selectImage(id1); saveAs("Tiff", {q(saved_tiff)});'),
    ]


def build_macro(
    fixture_path: Path,
    out_dir: Path,
    with_add: bool = True,
    last_step: str | None = None,
    exit_with: str = "script",
    threshold: str = THRESHOLD,
) -> tuple[str, list[Step]]:
    """Return (macro text, steps). `out_dir` receives dumps, done.json and the saved Tiff."""
    saved = out_dir / "saved" / f"{fixture_path.stem}-mask.tif"
    chosen = steps(fixture_path, saved, with_add, threshold)
    if last_step:
        chosen = chosen[: [s.tag for s in chosen].index(last_step) + 1]
    out = str(out_dir).replace("\\", "/")
    lines = [
        "// Fidelis reference macro (independent of the product generator); generated by verification/j12.py",
        f"// fixture: {fixture_path.name}",
        "function dump(tag) {",
        '  r = eval("js", "var DUMP_OUT=\'' + out + '\'; var DUMP_TAG=\'" + tag + "\'; var DUMP_RAW=true;\\n"'
        f" + File.openAsString({q(DUMPER)}));",
        f'  File.append(tag + ": " + r, {q(out_dir / "dumper.log")});',
        "}",
        f'File.makeDirectory({q(out_dir / "saved")});',
        f'setOption("BlackBackground", {str(BLACK_BACKGROUND).lower()});',
        'dump("s00_globals");',
    ]
    for step in chosen:
        lines.append(f"// {step.tag}: {step.label}")
        lines.append(step.macro)
        lines.append(f'dump("{step.tag}");')
    lines.append(f'File.saveString("{{}}", {q(out_dir / "done.json")});')
    if exit_with == "script":
        lines.append('eval("script", "System.exit(0);");')
    elif exit_with == "halt":  # GUI mode: System.exit can hang on the SciJava shutdown hook (P85)
        lines.append('eval("script", "java.lang.Runtime.getRuntime().halt(0);");')
    elif exit_with == "quit":
        lines.append('run("Quit");')
    return "\n".join(lines) + "\n", chosen


def describe(chosen: list[Step]) -> str:
    return json.dumps([s.__dict__ for s in chosen], indent=1)
